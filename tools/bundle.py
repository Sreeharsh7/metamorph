# Builds data/fallback.js: raw Cα (auth numbering) for the chain/range each level uses.
import json
exec(open('tools/inspect.py').read().split('pairs=')[0])
CFG = json.loads(open('js/states.js').read().split('STATES = ')[1].rstrip().rstrip(';'))
out = {}
for lvl, states in CFG.items():
    out[lvl] = {}
    for key, s in states.items():
        rows = [r for r in parse('tools/raw/%s.cif' % s['pdb'].lower())
                if r['group_PDB'] == 'ATOM' and r['auth_asym_id'] == s['chain'] and r['label_alt_id'] in ('.', 'A')]
        lo, hi = s['range']
        res = [[int(r['auth_seq_id']), round(float(r['Cartn_x']), 2), round(float(r['Cartn_y']), 2), round(float(r['Cartn_z']), 2)]
               for r in rows if lo <= int(r['auth_seq_id']) + s.get('offset', 0) <= hi]
        out[lvl][key] = res
        print(lvl, key, s['pdb'], len(res))
open('data/fallback.js', 'w').write('// Bundled Cα fallbacks (auth numbering), extracted from RCSB PDB model 1. Generated by tools/bundle.py.\nexport const FALLBACK = ' + json.dumps(out, separators=(',', ':')) + ';\n')
